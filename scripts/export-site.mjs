import { cp, mkdir, readFile, readdir, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Explicit destination keeps this command scoped to the intended site's public folder.
const siteRoot = process.argv[2];
if (!siteRoot) throw new Error('Usage: node scripts/export-site.mjs /absolute/path/to/toris-site');
const source = fileURLToPath(new URL('../apps/docs/dist/', import.meta.url));
const root = resolve(siteRoot);
const hosting = JSON.parse(await readFile(join(root, '.openai/hosting.json'), 'utf8'));
if (hosting.project_id !== 'appgprj_6a7796b257e48191a194f65fc3c61d18') {
  throw new Error('Destination is not the configured Toris Studio site.');
}
const html = await readFile(join(source, 'index.html'), 'utf8');
if (!html.includes('/torisui-kit/assets/'))
  throw new Error('Build the gallery with base=/torisui-kit/ first.');
const destination = join(root, 'public/torisui-kit');
await mkdir(destination, { recursive: true });
for (const entry of await readdir(source)) {
  await cp(join(source, entry), join(destination, entry), { recursive: true });
}
// Only prune stale Vite bundles generated by this gallery, preserving other files.
const currentAssets = new Set(await readdir(join(source, 'assets')));
for (const entry of await readdir(join(destination, 'assets'))) {
  if (/^index-[A-Za-z0-9_-]+\.(css|js)$/.test(entry) && !currentAssets.has(entry)) {
    await rm(join(destination, 'assets', entry));
  }
}
console.log(`Exported gallery to ${destination}`);
